80%라는 숫자 자체가 꼭 틀린 건 아니에요. 다만 "업계 표준이라서"는 근거가 못 됩니다.

근거가 "업계 표준"이라는 권위 하나뿐이에요. 업계 표준이 80%가 맞다고 쳐도, 거기서 곧바로 "전체 커버리지 80% 미만이면 CI 실패"가 나오지는 않아요. 새 코드에만 걸지, 전체에 걸지, 경고만 할지 같은 선택지가 중간에 빠져 있어요.

주장마다 근거를 따져 보면 이래요. 80%가 업계 표준이라는 주장이에요. 공식 표준은 없어요. 흔한 관례일 뿐이에요. SonarQube 기본 품질 게이트가 80%인데, 이건 전체가 아니라 새 코드 기준이에요. Google Testing Blog(2020)는 60% 괜찮음 · 75% 칭찬할 만함 · 90% 모범으로 구간만 제시했고, 회사 전체에 하나의 기준을 강제하지 않는다고 밝혔어요. "표준"은 과장이에요.

다음은 80% 게이트가 품질을 올린다는 주장이에요. 커버리지는 코드가 실행됐는지만 재요. 결과를 검증했는지는 재지 않아요. 목표 숫자가 되면 assert 없는 테스트로 숫자만 채우기 쉬워요(굿하트의 법칙).

숫자보다 영향이 큰 선택지가 있어요. 지금 안인 "전체 80%에 미달하면 실패" 방식은 레거시가 많으면 상관없는 PR까지 막혀요. 숫자 채우기용 테스트가 늘기 쉬워요. 변경된 코드만 80%로 보는 방식(diff coverage)은 새 코드에만 기준을 걸어요. 레거시는 고칠 때 자연스럽게 따라 올라가요. SonarQube 기본값도 이 방식이에요. 래칫(현재보다 떨어지면 실패) 방식은 기준을 정하는 논쟁이 없어요. 대신 올라가는 속도는 느려요.
EOF_C
